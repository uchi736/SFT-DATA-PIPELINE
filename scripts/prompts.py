"""
RAFT パイプライン用 LLM プロンプト定義モジュール

cpt-data-pipeline/scripts/prompts.py と同じ get_system_prompt / get_user_prompt
インタフェースを維持しつつ、RAFT 用（質問生成・CoT回答生成）に特化したプロンプトを定義。
全プロンプトの修正はこのファイルのみで行う。
"""

# 引用マーカー（formatting.py と一致させること）
QUOTE_OPEN = "##begin_quote##"
QUOTE_CLOSE = "##end_quote##"

# =============================================================================
# システムプロンプト
# =============================================================================

SYSTEM_PROMPTS = {
    # Phase1: チャンクから回答可能な質問を生成
    "raft_question": """あなたは技術文書から学習用の質問を作成する専門家です。
与えられた文書（コンテキスト）だけを根拠に、その内容を理解していないと答えられない質問を作成してください。

## ルール
- 質問は与えられた文書の情報だけで回答できるものにする
- 文書に書かれていない事柄を前提にした質問は作らない
- 「はい/いいえ」や一語で答えられる浅い質問は避ける
- 概念間の関係・仕組み・条件・比較など、理解を要する質問にする
- 質問文だけを出力し、回答や前置きは含めない
- 各質問は独立して読めるようにする（「この文書では」等の指示語に依存しない）""",

    # Phase2: ゴールデン文脈に基づく RAFT スタイル CoT 回答
    "raft_cot_answer": f"""あなたは根拠に基づいて段階的に推論する日本語アシスタントです。
与えられたコンテキスト（複数の文書）と質問に対し、思考過程（CoT）を示しながら回答してください。

## 回答の作り方
1. 質問に答えるのに必要な箇所を、コンテキストから**逐語で**引用する。
   引用は必ず {QUOTE_OPEN} と {QUOTE_CLOSE} で挟む。
   例: {QUOTE_OPEN} 実際の本文をそのままコピーした一節 {QUOTE_CLOSE}
2. 引用を踏まえて、なぜその答えになるのかを順を追って説明する。
3. 最後に結論となる最終回答を述べる。

## ルール
- 引用はコンテキスト中の文字列を改変せずそのまま使う（要約・言い換え不可）
- 引用は最低1箇所、`reasoning` の中に必ず含める
- コンテキストに無い情報を推測で補わない
- `reasoning` には推論と引用を、`final_answer` には簡潔な結論のみを書く""",
}


# =============================================================================
# ユーザープロンプトテンプレート
# =============================================================================

USER_PROMPTS = {
    # Phase1
    "raft_question": """以下の文書を読み、その内容だけで回答できる質問を {num_questions} 個作成してください。

【文書】
{text}
""",

    # Phase2（根拠文書=コンテキストはオラクル1件。引用はこの本文から）
    "raft_cot_answer": """以下のコンテキスト（根拠文書）を参照し、質問に対して引用付きの思考過程と最終回答を作成してください。
引用は必ずこのコンテキスト本文から逐語で行ってください。

【コンテキスト】
{context}

【質問】
{question}
""",
}


# 修復リトライ時に付与する追記指示（gen モジュールが利用）
REPAIR_HINTS = {
    "json": "出力は指定スキーマに厳密に従う有効なJSONのみとし、余計なテキストを含めないでください。",
    "quote": (
        f"reasoning には必ずコンテキストからの逐語引用を {QUOTE_OPEN} と {QUOTE_CLOSE} "
        "で挟んで最低1箇所含めてください。引用は本文をそのままコピーすること。"
    ),
}


# =============================================================================
# ヘルパー関数（cpt-data-pipeline と同一インタフェース）
# =============================================================================

def get_system_prompt(name: str) -> str:
    """システムプロンプトを取得"""
    return SYSTEM_PROMPTS.get(name, "")


def get_user_prompt(name: str, **kwargs) -> str:
    """ユーザープロンプトを取得し、変数を埋め込む"""
    template = USER_PROMPTS.get(name, "")
    if not template:
        return ""
    try:
        return template.format(**kwargs)
    except KeyError as e:
        raise ValueError(f"プロンプト '{name}' に必要な変数が不足しています: {e}")
